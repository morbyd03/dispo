def env_bool(nom, defaut=False):
    valeur = os.environ.get(nom, str(defaut)).strip().lower()

    if valeur in ("1", "true", "yes", "on"):
        return True

    if valeur in ("0", "false", "no", "off"):
        return False

    raise ImproperlyConfigured(
        f"{nom} : valeur booleenne invalide."
    )


def env_list(nom, defaut=""):
    return [
        valeur.strip()
        for valeur in os.environ.get(nom, defaut).split(",")
        if valeur.strip()
    ]


